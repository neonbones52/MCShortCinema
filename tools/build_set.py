"""One command from a set script to an OBJ ready for Blender:

    python tools/build_set.py test_farm

1. runs sets/<name>.py with the MCBuilder venv  -> assets/sets/<name>.schem
2. writes sets/<name>.mwscript and runs Mineways headless -> assets/sets/obj/<name>.obj (+ tex/)
Textures come from assets/mineways/terrainExt_26_2.png (built from the 26.2 jar).
In Blender: import with forward -Z / up Y, then MCprep prep_materials with
animateTextures=False (otherwise MCprep swaps in textures from its own old pack).
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MCB_PY = r"C:\Games\MCBuilder\venv\Scripts\python.exe"
MINEWAYS = r"C:\Games\mineways\Mineways.exe"
TERRAIN = os.path.join(ROOT, "assets", "mineways", "terrainExt_26_2.png")

SCRIPT = """// generated by tools/build_set.py
Minecraft world: {schem}
Terrain file name: {terrain}
Selection location: all
Set render type: Wavefront OBJ absolute indices
File type: Export individual textures to directory tex
Texture output RGB: YES
Texture output A: YES
Texture output RGBA: YES
Export separate types: YES
Material per family: YES
Split by block type: YES
Make groups objects: no
Custom material: YES
Export lesser blocks: YES
Fatten lesser blocks: no
Double all billboard faces: no
Center model: no
Create block faces at the borders: no
Make Z the up direction instead of Y: no
Export for rendering: {obj}
"""


def build(name):
    schem = os.path.join(ROOT, "assets", "sets", name + ".schem")
    obj_dir = os.path.join(ROOT, "assets", "sets", "obj")
    obj = os.path.join(obj_dir, name + ".obj")
    os.makedirs(obj_dir, exist_ok=True)
    subprocess.run([MCB_PY, os.path.join(ROOT, "sets", name + ".py")], check=True)
    mw = os.path.join(ROOT, "sets", name + ".mwscript")
    with open(mw, "w", encoding="utf-8") as f:
        f.write(SCRIPT.format(schem=schem, terrain=TERRAIN, obj=obj))
    log = os.path.join(obj_dir, name + "_mineways.log")
    # -s none: no saves folder needed (we open .schem files; TLauncher saves are elsewhere)
    res = subprocess.run([MINEWAYS, "-headless", "-s", "none", "-l", log, mw], capture_output=True, text=True)
    warn = [l for l in (res.stderr or "").splitlines() if "WARN" in l.upper() or "ERROR" in l.upper()]
    print("\n".join(warn) if warn else "mineways: ok")
    print("obj:", obj, "exists" if os.path.exists(obj) else "MISSING")


if __name__ == "__main__":
    build(sys.argv[1])
